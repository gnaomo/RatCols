#!/usr/bin/env python3
"""
survey_collision_ids.py

LLM-generated by Claude

Walk every level's collision/mesh.glb (Wrench R&C export layout) and report
which collision material IDs (e.g. col_00, col_01, ... col_ff) show up in
each level, and how many faces (triangles) use each one.

Pure stdlib -- no pip installs needed. Only reads the JSON chunk of each
.glb (accessor "count" fields), never touches the binary vertex/index data,
so it's fast even on hundreds of files.

Expected layout (matches your `levels/` dir):
  <root>/<level_dir>/chunks/<chunk_n>/collision/mesh.glb
(faces from every chunk in a level are summed together into one level total)

Usage:
  python3 survey_collision_ids.py                        # run from inside .../levels
  python3 survey_collision_ids.py /path/to/levels
  python3 survey_collision_ids.py --group-by material     # pivot: material -> which levels use it
  python3 survey_collision_ids.py --sort faces            # sort tables by face count (default: name)
  python3 survey_collision_ids.py --csv report.csv --json report.json
"""
import argparse
import json
import re
import struct
import sys
from pathlib import Path
from collections import defaultdict, OrderedDict

GLB_MAGIC = b"glTF"
CHUNK_JSON = 0x4E4F534A


class GlbParseError(Exception):
    pass


def read_glb_json(path: Path) -> dict:
    """Read only the JSON chunk of a .glb file and return the parsed dict."""
    with open(path, "rb") as f:
        header = f.read(12)
        if len(header) < 12:
            raise GlbParseError("file too small to be a glb")
        magic, version, total_len = struct.unpack("<4sII", header)
        if magic != GLB_MAGIC:
            raise GlbParseError(f"bad magic {magic!r} (not a glb)")

        json_bytes = None
        while f.tell() < total_len:
            chunk_header = f.read(8)
            if len(chunk_header) < 8:
                break
            chunk_len, chunk_type = struct.unpack("<II", chunk_header)
            data = f.read(chunk_len)
            if chunk_type == CHUNK_JSON:
                json_bytes = data
                break  # don't bother reading the BIN chunk at all
        if json_bytes is None:
            raise GlbParseError("no JSON chunk found")
        return json.loads(json_bytes.decode("utf-8"))


COL_NAME_RE = re.compile(r"^col_([0-9a-fA-F]+)$")


def normalize_material_name(name: str, nibble: str = "full") -> str:
    """
    col_5 -> col_05, col_1f -> col_1f (nibble="full", default: zero-padded full id)
    col_42 -> col_2, col_5f -> col_f  (nibble="low": second hex digit only)
    col_42 -> col_4, col_5f -> col_5  (nibble="high": first hex digit only)
    Anything not matching col_<hex> (e.g. hero_group_collision) is unchanged either way.
    """
    m = COL_NAME_RE.match(name)
    if not m:
        return name
    value = int(m.group(1), 16) & 0xFF  # collision ids are 0-255 (one byte)
    if nibble == "low":
        return f"col_{value & 0xF:x}"
    if nibble == "high":
        return f"col_{(value >> 4) & 0xF:x}"
    return f"col_{value:02x}"


def analyze_glb(path: Path, nibble: str = "full"):
    """Returns (per_material: dict[name] -> {"faces": int, "verts": int}, warnings: list[str])"""
    gltf = read_glb_json(path)
    accessors = gltf.get("accessors", [])
    materials = gltf.get("materials", [])
    meshes = gltf.get("meshes", [])

    per_material = defaultdict(lambda: {"faces": 0, "verts": 0})
    warnings = []

    for mesh_idx, mesh in enumerate(meshes):
        for prim_idx, prim in enumerate(mesh.get("primitives", [])):
            mode = prim.get("mode", 4)  # 4 = TRIANGLES (glTF default)
            mat_idx = prim.get("material")
            if mat_idx is None:
                mat_name = "NO_MATERIAL"
            else:
                try:
                    mat_name = materials[mat_idx].get("name", f"material_{mat_idx}")
                except IndexError:
                    mat_name = f"INVALID_MATERIAL_{mat_idx}"
                    warnings.append(f"{path}: mesh#{mesh_idx} prim#{prim_idx}: material index {mat_idx} out of range")
            mat_name = normalize_material_name(mat_name, nibble)

            pos_accessor_idx = prim.get("attributes", {}).get("POSITION")
            vcount = accessors[pos_accessor_idx]["count"] if pos_accessor_idx is not None else 0

            indices_idx = prim.get("indices")
            idx_count = accessors[indices_idx]["count"] if indices_idx is not None else vcount

            if mode == 4:  # TRIANGLES
                face_count = idx_count // 3
            elif mode in (5, 6):  # TRIANGLE_STRIP / TRIANGLE_FAN
                face_count = max(idx_count - 2, 0)
                warnings.append(f"{path}: mesh#{mesh_idx} prim#{prim_idx}: non-list triangle mode ({mode}), face count is approximate")
            else:
                face_count = 0
                warnings.append(f"{path}: mesh#{mesh_idx} prim#{prim_idx}: unsupported primitive mode {mode}, skipped from face counts")

            entry = per_material[mat_name]
            entry["faces"] += face_count
            entry["verts"] += vcount

    return per_material, warnings


NATURAL_LEVEL_RE = re.compile(r"^(\d+)_(.*)$")


def natural_level_key(name: str):
    m = NATURAL_LEVEL_RE.match(name)
    return (int(m.group(1)) if m else 999, name)


def display_level_name(name: str) -> str:
    """0_veldin_tutorial -> 00_veldin_tutorial (zero-padded number prefix)."""
    m = NATURAL_LEVEL_RE.match(name)
    if not m:
        return name
    return f"{int(m.group(1)):02d}_{m.group(2)}"


def find_level_dirs(root: Path):
    dirs = [p for p in root.iterdir() if p.is_dir() and NATURAL_LEVEL_RE.match(p.name)]
    return sorted(dirs, key=lambda p: natural_level_key(p.name))


def find_collision_glbs(level_dir: Path):
    """<level_dir>/chunks/*/collision/mesh.glb"""
    chunks_dir = level_dir / "chunks"
    if not chunks_dir.is_dir():
        return []
    results = []
    for chunk_dir in sorted(chunks_dir.iterdir(), key=lambda p: (len(p.name), p.name)):
        glb = chunk_dir / "collision" / "mesh.glb"
        if glb.is_file():
            results.append(glb)
    return results


def fmt_int(n):
    return f"{n:,}"


def sort_items(items, sort_mode):
    if sort_mode == "faces":
        return sorted(items, key=lambda kv: kv[1]["faces"], reverse=True)
    return sorted(items, key=lambda kv: kv[0])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", nargs="?", default=".", help="path to the levels/ directory (default: current dir)")
    ap.add_argument("--csv", help="write a CSV report to this path (column order follows --group-by: "
                                   "level,material,... by default, or material,level,... with --group-by material)")
    ap.add_argument("--json", help="write a full JSON report to this path")
    ap.add_argument("--sort", choices=["name", "faces"], default="name", help="sort tables by (default: name)")
    ap.add_argument("--group-by", choices=["level", "material"], default="level",
                     help="'level' (default): one section per level, listing materials inside it. "
                          "'material': one section per collision id, listing which levels use it")
    ap.add_argument("--nibble", choices=["full", "low", "high"], default="full",
                     help="'full' (default): use the whole id (col_5f). "
                          "'low': collapse to just the second hex digit (col_42 and col_a2 both -> col_2) -- "
                          "e.g. to test the theory that this digit encodes collision type (water/lava/acid/normal). "
                          "'high': collapse to just the first hex digit (col_42 and col_4f both -> col_4) -- "
                          "e.g. to test the theory that this digit encodes sound/other flags.")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"error: {root} is not a directory", file=sys.stderr)
        sys.exit(1)

    level_dirs = find_level_dirs(root)
    if not level_dirs:
        print(f"error: no level directories (e.g. '0_veldin_tutorial') found under {root}", file=sys.stderr)
        sys.exit(1)

    all_warnings = []
    # data[level_name][material] = {"faces": int, "verts": int}
    data = OrderedDict()

    print(f"Scanning {len(level_dirs)} level(s) under {root}")
    if args.nibble != "full":
        which = "second hex digit only (low nibble)" if args.nibble == "low" else "first hex digit only (high nibble)"
        print(f"Grouping collision ids by: {which} -- e.g. col_5f -> col_{'f' if args.nibble == 'low' else '5'}")
    print()

    for level_dir in level_dirs:
        glbs = find_collision_glbs(level_dir)
        level_totals = defaultdict(lambda: {"faces": 0, "verts": 0})

        if not glbs:
            data[level_dir.name] = level_totals
            continue

        for glb_path in glbs:
            try:
                per_material, warnings = analyze_glb(glb_path, args.nibble)
            except GlbParseError as e:
                all_warnings.append(f"{glb_path}: failed to parse ({e})")
                continue
            all_warnings.extend(warnings)
            for mat_name, stats in per_material.items():
                lt = level_totals[mat_name]
                lt["faces"] += stats["faces"]
                lt["verts"] += stats["verts"]

        data[level_dir.name] = level_totals

    # material -> {level_name: {"faces":.., "verts":..}}  (used by group-by=material console view and CSV)
    by_material = defaultdict(dict)
    for level_name, level_totals in data.items():
        for mat_name, stats in level_totals.items():
            by_material[mat_name][level_name] = stats
    mat_totals = {
        mat: {"faces": sum(s["faces"] for s in levels.values()),
              "verts": sum(s["verts"] for s in levels.values())}
        for mat, levels in by_material.items()
    }

    # ---- console output ----
    if args.group_by == "level":
        for level_name, level_totals in data.items():
            dname = display_level_name(level_name)
            if not level_totals:
                print(f"== {dname} == (no collision/mesh.glb found)\n")
                continue
            print(f"== {dname} ==")
            for mat_name, stats in sort_items(level_totals.items(), args.sort):
                print(f"    {mat_name:<10} faces={fmt_int(stats['faces']):>9}  verts={fmt_int(stats['verts']):>9}")
            print()
    else:  # group-by material
        for mat_name, _ in sort_items(mat_totals.items(), args.sort):
            levels = by_material[mat_name]
            print(f"== {mat_name} ==  (used in {len(levels)} level(s))")
            level_items = sorted(levels.items(), key=lambda kv: natural_level_key(kv[0]))
            for level_name, stats in level_items:
                print(f"    {display_level_name(level_name):<22} faces={fmt_int(stats['faces']):>9}  verts={fmt_int(stats['verts']):>9}")
            print()

    # ---- grand total across all levels ----
    grand_total = defaultdict(lambda: {"faces": 0, "verts": 0, "levels": set()})
    for level_name, level_totals in data.items():
        for mat_name, stats in level_totals.items():
            gt = grand_total[mat_name]
            gt["faces"] += stats["faces"]
            gt["verts"] += stats["verts"]
            gt["levels"].add(level_name)

    print("== GRAND TOTAL (all levels) ==")
    for mat_name, stats in sorted(grand_total.items(), key=lambda kv: kv[1]["faces"], reverse=True):
        print(f"    {mat_name:<10} faces={fmt_int(stats['faces']):>10}  used in {len(stats['levels'])} level(s)")
    print()

    if all_warnings:
        print(f"({len(all_warnings)} warning(s) during parsing -- run with --json to capture details)")

    # ---- CSV / JSON exports ----
    if args.csv:
        import csv as csvmod
        with open(args.csv, "w", newline="") as f:
            if args.group_by == "material":
                # grouped by collision id first: material, level, faces, verts -- rows for
                # the same material are written together, in the same order as the console view
                writer = csvmod.DictWriter(f, fieldnames=["material", "level", "faces", "verts"])
                writer.writeheader()
                for mat_name, _ in sort_items(mat_totals.items(), args.sort):
                    level_items = sorted(by_material[mat_name].items(), key=lambda kv: natural_level_key(kv[0]))
                    for level_name, stats in level_items:
                        writer.writerow({"material": mat_name, "level": display_level_name(level_name),
                                          "faces": stats["faces"], "verts": stats["verts"]})
            else:
                # grouped by level first (original flat layout): level, material, faces, verts
                writer = csvmod.DictWriter(f, fieldnames=["level", "material", "faces", "verts"])
                writer.writeheader()
                for level_name, level_totals in data.items():
                    for mat_name, stats in sort_items(level_totals.items(), args.sort):
                        writer.writerow({"level": display_level_name(level_name), "material": mat_name,
                                          "faces": stats["faces"], "verts": stats["verts"]})
        print(f"CSV written to {args.csv}")

    if args.json:
        json_report = OrderedDict()
        for level_name, level_totals in data.items():
            json_report[display_level_name(level_name)] = {
                mat: {"faces": s["faces"], "verts": s["verts"]} for mat, s in level_totals.items()
            }
        json_report["_grand_total"] = {
            mat: {"faces": s["faces"], "verts": s["verts"], "levels": sorted(display_level_name(n) for n in s["levels"])}
            for mat, s in grand_total.items()
        }
        json_report["_warnings"] = all_warnings
        with open(args.json, "w") as f:
            json.dump(json_report, f, indent=2)
        print(f"JSON written to {args.json}")


if __name__ == "__main__":
    main()
